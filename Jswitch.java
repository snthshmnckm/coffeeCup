public class Jswitch {
    public static void main(String[] args) {
        int choice = 9;
        switch (choice) {
            case 1:
                System.out.println("onnu");
                break;
            case 2:
            System.out.println("rendu");
            break;
            case 9:
            System.out.println("ombothu");  
            break;
            default:
            System.out.println("edume illa");
                break;
        }
    }
}